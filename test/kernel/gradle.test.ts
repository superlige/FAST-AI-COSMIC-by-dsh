import { describe, expect, it } from "vitest";
import { detect } from "../../src/kernel/config/detect.ts";
import {
	applyModuleOverrides,
	decomment,
	moduleDir,
	moduleRoot,
	parseIncludes,
	parseProjectDeps,
	parseProjectDirs,
	pickModules,
	resolveCodeModules,
} from "../../src/kernel/config/gradle.ts";

/* Shared corpus. Every entry exists because the frozen CLI comments name it as a
 * spelling that, when unsupported, produced a silent wrong answer. */
const SETTINGS_CORPUS = [
	"include(\n 'zlgd-cosmic-debug',\n ':zlgd-hhx',\n)",
	"include 'a', 'b'\ninclude ':c'",
	"// include 'commented-out'\ninclude 'real'",
	"/* include 'block' */ include(':kept')",
	"include(':group:nested')",
	"include 'a',\n  'b',\n  'c'\nrootProject.name = 'x'",
	"",
	"rootProject.name = 'no-includes'",
] as const;

const BUILD_CORPUS = [
	"dependencies { implementation project(':a') }",
	'dependencies { implementation project("b") }',
	"dependencies { implementation project(path: ':c', configuration: 'shadow') }",
	"dependencies { implementation projects.zlgdHhx }",
	"dependencies { implementation projects.notAModule }",
	"dependencies { implementation project(':g:m') }",
	"// implementation project(':commented')\nimplementation project(':live')",
	"",
] as const;

const KNOWN = ["zlgd-hhx", "zlgd_common", "a", "b", "c", "g:m", "live"] as const;

describe("S2.1 gradle parsing", () => {
	it("parses every include spelling in the corpus", () => {
		expect(parseIncludes(SETTINGS_CORPUS[0])).toEqual(["zlgd-cosmic-debug", "zlgd-hhx"]);
		expect(parseIncludes(SETTINGS_CORPUS[1])).toEqual(["a", "b", "c"]);
		expect(parseIncludes(SETTINGS_CORPUS[2])).toEqual(["real"]);
		expect(parseIncludes(SETTINGS_CORPUS[3])).toEqual(["kept"]);
		expect(parseIncludes(SETTINGS_CORPUS[4])).toEqual(["group:nested"]);
		expect(parseIncludes(SETTINGS_CORPUS[5])).toEqual(["a", "b", "c"]);
		expect(parseIncludes("")).toEqual([]);
	});

	it("recognizes all four project dependency spellings and never guesses an accessor", () => {
		expect(parseProjectDeps(BUILD_CORPUS[0], KNOWN).deps).toEqual(["a"]);
		expect(parseProjectDeps(BUILD_CORPUS[1], KNOWN).deps).toEqual(["b"]);
		expect(parseProjectDeps(BUILD_CORPUS[2], KNOWN).deps).toEqual(["c"]);
		// projects.zlgdHhx flattens to the same shape as zlgd-hhx: a unique hit.
		expect(parseProjectDeps(BUILD_CORPUS[3], KNOWN).deps).toEqual(["zlgd-hhx"]);
		// No unique hit must go to unresolved rather than being guessed.
		const ambiguous = parseProjectDeps(BUILD_CORPUS[4], KNOWN);
		expect(ambiguous.deps).toEqual([]);
		expect(ambiguous.unresolved).toEqual(["projects.notAModule"]);
	});

	it("collects code modules along the transitive closure, not just direct deps", () => {
		// debug -> business -> shared. Direct-only resolution silently drops "shared",
		// whose symptom is that edits to it have no effect.
		const gradle: Record<string, string> = {
			debug: "dependencies { implementation project(':business') }",
			business: "dependencies { implementation project(':shared') }",
			shared: "",
		};
		const result = resolveCodeModules("debug", (m) => gradle[m] ?? "", ["debug", "business", "shared"]);
		expect(result.modules).toEqual(["business", "shared"]);
	});

	it("terminates on a dependency cycle", () => {
		const gradle: Record<string, string> = {
			a: "project(':b')",
			b: "project(':a')",
		};
		expect(resolveCodeModules("a", (m) => gradle[m] ?? "", ["a", "b"]).modules).toEqual(["b"]);
	});

	it("maps nested module names to directories only in moduleDir", () => {
		expect(moduleDir(":group:nested")).toBe("group/nested");
		expect(moduleDir("plain")).toBe("plain");
		expect(moduleDir(null)).toBe("");
	});

	it("keeps add/remove overrides growing with detection", () => {
		// Wholesale replacement alone lets config go stale when the project gains a module.
		const detected = ["a", "b"];
		expect(applyModuleOverrides(detected, {}).modules).toEqual(["a", "b"]);
		expect(applyModuleOverrides(detected, { extraCodeModules: "c" }).modules).toEqual(["a", "b", "c"]);
		expect(applyModuleOverrides(detected, { excludeCodeModules: ["b"] }).modules).toEqual(["a"]);
		const explicit = applyModuleOverrides(detected, { codeModules: ["x"], extraCodeModules: ["y"] });
		expect(explicit.modules).toEqual(["x", "y"]);
		expect(explicit.explicit).toBe(true);
	});

	it("rejects an unknown --module instead of silently skipping it", () => {
		expect(pickModules(["--module", "a,b"], ["a", "b", "c"]).modules).toEqual(["a", "b"]);
		expect(pickModules([], ["a"]).scoped).toBe(false);
		const bad = pickModules(["--module=zzz"], ["a"]);
		expect(bad.modules).toBeNull();
		expect(bad.bad).toEqual(["zzz"]);
	});

	it("follows projectDir relocations as the dev-assistant template writes them", () => {
		const settings = [
			"/**\n * generated by the Kingdee cosmic development assistant plugin\n */",
			"include(\n\t\t':demo-cosmic-debug',\n\t\t':demo-base',\n\n\t\t':demo-fi',\n)",
			"project(':demo-cosmic-debug').projectDir = new File('code/demo-cosmic-debug')",
			"project(':demo-base').projectDir = new File(rootDir, 'code/base/demo-base/')",
			'project(":demo-fi").projectDir = file("./code/fi/demo-fi")',
			"// project(':demo-old').projectDir = new File('code/old')",
		].join("\n");
		expect(parseIncludes(settings)).toEqual(["demo-cosmic-debug", "demo-base", "demo-fi"]);
		const dirs = parseProjectDirs(settings);
		expect(dirs).toEqual({
			"demo-cosmic-debug": "code/demo-cosmic-debug",
			"demo-base": "code/base/demo-base",
			"demo-fi": "code/fi/demo-fi",
		});
		expect(moduleDir(":demo-fi", dirs)).toBe("code/fi/demo-fi");
		expect(moduleDir("group:nested", dirs)).toBe("group/nested");
		expect(moduleRoot("/proj", "demo-base", dirs).replace(/\\/g, "/")).toBe("/proj/code/base/demo-base");
		expect(moduleRoot("/proj", "x", { x: "E:/elsewhere/x" })).toBe("E:/elsewhere/x");

		// Detection reads the debug module's build.gradle where it really is, so code modules are found.
		const files: Record<string, string> = {
			"/proj/settings.gradle": settings,
			"/proj/code/demo-cosmic-debug/build.gradle":
				"plugins { id 'java-application-conventions' }\ndependencies { implementation project(':demo-fi') }",
			"/proj/code/fi/demo-fi/build.gradle": "dependencies { implementation project(':demo-base') }",
		};
		const auto = detect("/proj", {
			read: (path) => files[path.replace(/\\/g, "/")] ?? "",
			listJavaFiles: () => [],
		});
		expect(auto.debugModule).toBe("demo-cosmic-debug");
		expect(auto.codeModules).toEqual(["demo-fi", "demo-base"]);
		expect(auto.moduleDirs["demo-fi"]).toBe("code/fi/demo-fi");
	});

	it("strips comments without eating a protocol-relative URL", () => {
		expect(decomment("a // b").trim()).toBe("a");
		expect(decomment("url = 'http://x/y'")).toContain("http://x/y");
	});
});
