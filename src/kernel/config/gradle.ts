/**
 * Gradle text parsing. Ported from the frozen ref tools/modules.mjs (c7b8815);
 * pure text in, pure data out -- no filesystem, no environment, no module-level
 * state. Behaviour is deliberately identical to the frozen CLI: every rule below
 * exists because its absence produced a silent wrong answer, and the comments
 * record which one.
 *
 * "Code module" means a local Gradle subproject (where sources live, where
 * classes compile to, which jars deploy). It is NOT a Cosmic business
 * module/app: one Gradle module can span several clouds, and the plugins of one
 * bill can be spread over several modules. Real ownership is only ever looked up.
 */

import { isAbsolute, join } from "node:path";

/** Strips block and line comments so a commented-out include/project is not read as config. */
export function decomment(source: string | null | undefined): string {
	return String(source ?? "")
		.replace(/\/\*[\s\S]*?\*\//g, "")
		.replace(/(^|[^:])\/\/.*$/gm, "$1");
}

/** Module name to its directory as settings.gradle relocates it, relative to the project root (or absolute). */
export type ModuleDirMap = Readonly<Record<string, string>>;

/**
 * Gradle path to disk directory: a nested module `a:b` lives in `a/b`, unless
 * settings.gradle moved it with `projectDir` (see `parseProjectDirs`). Converted only here.
 */
export function moduleDir(module: string | null | undefined, dirs: ModuleDirMap = {}): string {
	const name = norm(module);
	const moved = dirs[name];
	if (moved !== undefined) return moved;
	return name.split(":").join("/");
}

/** The module's directory on disk: a relocated absolute directory as is, everything else under the project root. */
export function moduleRoot(root: string, module: string | null | undefined, dirs: ModuleDirMap = {}): string {
	const dir = moduleDir(module, dirs);
	return isAbsolute(dir) || /^[A-Za-z]:\//.test(dir) ? dir : join(root, dir);
}

/**
 * `project(':a').projectDir = new File('code/a')` lines from settings.gradle.
 *
 * Templates generated by the Kingdee dev assistant keep every module under
 * `code/<cloud>/`. Without this map every path derived from a module name points
 * at `<root>/<module>`, which does not exist: detection finds no code modules,
 * and source lookup, lint and freshness all scan empty directories.
 * Accepted right-hand sides: `new File('x')`, `new File(rootDir|settingsDir, 'x')`, `file('x')`.
 */
export function parseProjectDirs(settingsText: string | null | undefined): Record<string, string> {
	const text = decomment(settingsText);
	const out: Record<string, string> = {};
	const re =
		/\bproject\s*\(\s*['"](:?[A-Za-z0-9_.\-:]+)['"]\s*\)\s*\.projectDir\s*=\s*(?:new\s+File\s*\(\s*(?:(?:rootDir|settingsDir)\s*,\s*)?|file\s*\(\s*)['"]([^'"]+)['"]\s*\)/g;
	for (const match of text.matchAll(re)) {
		const name = norm(match[1]);
		const dir = (match[2] ?? "").trim().replace(/\\/g, "/").replace(/^\.\//, "").replace(/\/+$/, "");
		if (name !== "" && dir !== "") out[name] = dir;
	}
	return out;
}

/** Normalizes a module name: `:a:b` and `a:b` are the same module. */
function norm(module: string | null | undefined): string {
	return String(module ?? "")
		.trim()
		.replace(/^:+/, "");
}

function uniq(list: readonly string[]): string[] {
	const out: string[] = [];
	for (const item of list) if (item && !out.includes(item)) out.push(item);
	return out;
}

function asList(value: unknown): string[] {
	const raw = Array.isArray(value) ? value : typeof value === "string" ? value.split(",") : [];
	return raw.map((item) => norm(String(item))).filter((item) => item.length > 0);
}

/** include list from settings.gradle -- both bracketed and bare spellings are accepted. */
export function parseIncludes(settingsText: string | null | undefined): string[] {
	const text = decomment(settingsText);
	const out: string[] = [];
	const re = /\binclude\b/g;
	let match: RegExpExecArray | null = re.exec(text);
	while (match !== null) {
		// Followed by "(" -> consume to the matching ")", otherwise to end of line
		// (which may carry continuation commas).
		const rest = text.slice(match.index + match[0].length);
		let segment: string;
		if (/^\s*\(/.test(rest)) {
			const open = rest.indexOf("(");
			const close = rest.indexOf(")", open);
			segment = close < 0 ? rest : rest.slice(open + 1, close);
		} else {
			const stop = /\n\s*(?![\s'",])/.exec(rest);
			segment = stop ? rest.slice(0, stop.index) : (rest.split("\n")[0] ?? "");
		}
		for (const quoted of segment.match(/['"]:?[A-Za-z0-9_.\-:]+['"]/g) ?? []) {
			const name = norm(quoted.slice(1, -1));
			if (name && !out.includes(name)) out.push(name);
		}
		match = re.exec(text);
	}
	return out;
}

export interface ProjectDeps {
	deps: string[];
	unresolved: string[];
}

/**
 * Project dependencies declared in one build.gradle. All four spellings must be
 * recognized: reading only the plain string form leaves projects that use the
 * others with no detected modules, and the symptom ("fast cannot find this
 * class", "deploy is missing a jar") never points at configuration.
 *
 * @param known the settings.gradle include list. Needed ONLY for type-safe
 * accessors: a `projects.zlgdHhx` reference is a Gradle-generated camel name
 * that cannot be reversed (zlgd-hhx / zlgd_hhx / zlgd.hhx normalize alike), so
 * it is matched against real module names. No unique match goes to `unresolved`
 * for doctor to report -- it is never guessed.
 */
export function parseProjectDeps(
	buildGradleText: string | null | undefined,
	known: readonly string[] = [],
): ProjectDeps {
	const text = decomment(buildGradleText);
	const deps: string[] = [];
	const unresolved: string[] = [];
	// project(':a') / project("a") / project(path: ':a', configuration: 'x') / project(':g:m')
	for (const match of text.matchAll(/\bproject\s*\(\s*(?:path\s*:\s*)?['"]:?([A-Za-z0-9_.\-:]+)['"]/g)) {
		deps.push(norm(match[1]));
	}
	for (const match of text.matchAll(/\bprojects\.([A-Za-z0-9_]+(?:\.[A-Za-z0-9_]+)*)/g)) {
		const raw = match[1] ?? "";
		const flat = raw.replace(/\./g, "").toLowerCase();
		const hit = known.filter((k) => k.replace(/[^A-Za-z0-9]/g, "").toLowerCase() === flat);
		if (hit.length === 1) deps.push(norm(hit[0]));
		else unresolved.push(`projects.${raw}`);
	}
	return { deps: uniq(deps), unresolved: uniq(unresolved) };
}

export interface CodeModuleResolution {
	modules: string[];
	unresolved: string[];
}

/**
 * Code modules = the projects the debug module depends on, collected along the
 * transitive closure. Direct dependencies alone miss the shared module in
 * "debug -> business -> shared", yet its classes still need to be on the
 * classpath, fast-compiled and deployed. The symptom of missing it is that edits
 * to the shared module have no effect, with no error at all.
 *
 * @param readGradle module name to its build.gradle text (empty string if unreadable)
 */
export function resolveCodeModules(
	debugModule: string,
	readGradle: (module: string) => string,
	known: readonly string[] = [],
): CodeModuleResolution {
	const modules: string[] = [];
	const unresolved: string[] = [];
	const seen = new Set([norm(debugModule)]);
	const queue = [norm(debugModule)];
	while (queue.length > 0) {
		const current = queue.shift() as string;
		const result = parseProjectDeps(readGradle(current) || "", known);
		for (const item of result.unresolved) {
			const line = `${current}: ${item}`;
			if (!unresolved.includes(line)) unresolved.push(line);
		}
		for (const dep of result.deps) {
			if (seen.has(dep)) continue;
			seen.add(dep);
			modules.push(dep);
			queue.push(dep);
		}
	}
	return { modules, unresolved };
}

export interface ModuleOverrideInput {
	codeModules?: unknown;
	extraCodeModules?: unknown;
	excludeCodeModules?: unknown;
}

export interface ModuleOverrideResult {
	modules: string[];
	explicit: boolean;
	extra: string[];
	exclude: string[];
	source: string;
}

/**
 * Detection result + user config -> final list.
 *
 * `codeModules` replaces wholesale, and `extraCodeModules` / `excludeCodeModules`
 * add and remove on top of detection. Replacement alone lets config go quietly
 * stale: detection would find a newly added module, the hardcoded list will not,
 * and the new module is then neither compiled nor deployed -- again with no error.
 */
export function applyModuleOverrides(
	detected: readonly string[] | string | null | undefined,
	user: ModuleOverrideInput = {},
): ModuleOverrideResult {
	const explicit = asList(user.codeModules);
	const extra = asList(user.extraCodeModules);
	const exclude = asList(user.excludeCodeModules);
	const base = explicit.length > 0 ? explicit : asList(detected);
	const modules = uniq([...base, ...extra]).filter((m) => !exclude.includes(m));
	const bits: string[] = [explicit.length > 0 ? "config.json" : "自动探测"];
	if (extra.length > 0) bits.push(`+${extra.length}`);
	if (exclude.length > 0) bits.push(`-${exclude.length}`);
	const source = bits.length > 1 ? `${bits[0]}（config.json ${bits.slice(1).join(" ")}）` : (bits[0] as string);
	return { modules, explicit: explicit.length > 0, extra, exclude, source };
}

export type ModulePick =
	| { modules: string[]; scoped: boolean; bad?: undefined; error?: undefined }
	| { modules: null; scoped: true; bad: string[]; error: string };

/**
 * Parses and validates `--module a,b`. An unrecognized name is an error listing
 * the valid options, never a silent skip -- skipping means "build reported
 * success but that module was not compiled".
 */
export function pickModules(argv: readonly string[], all: readonly string[]): ModulePick {
	const want: string[] = [];
	for (let i = 0; i < argv.length; i++) {
		const arg = argv[i] as string;
		if (arg === "--module" || arg === "-m") {
			i += 1;
			want.push(...asList(argv[i]));
		} else if (arg.startsWith("--module=")) {
			want.push(...asList(arg.slice("--module=".length)));
		}
	}
	if (want.length === 0) return { modules: [...all], scoped: false };
	const bad = want.filter((m) => !all.includes(m));
	if (bad.length > 0) {
		return { modules: null, scoped: true, bad, error: `不是已配置的代码模块：${bad.join(", ")}` };
	}
	return { modules: uniq(want), scoped: true };
}
