/**
 * Project auto-detection. Ported from the frozen ref config.mjs (c7b8815).
 *
 * Design rule inherited verbatim from the frozen CLI: anything that can be
 * detected is never asked for, and anything that fails silently when wrong is
 * never given a default. The filesystem is reached through an injected port so
 * detection stays testable and so a resident agent can never read a directory
 * outside the project root it was handed.
 */
import { type Dirent, readdirSync, readFileSync } from "node:fs";
import { basename, join } from "node:path";
import {
	decomment,
	type ModuleDirMap,
	moduleRoot,
	parseIncludes,
	parseProjectDirs,
	resolveCodeModules,
} from "./gradle.ts";

export interface FileSystemPort {
	/** Returns file text, or "" when unreadable -- matching the frozen `read` helper. */
	read(absolutePath: string): string;
	/** Recursively lists .java files under a directory; missing directories yield []. */
	listJavaFiles(absoluteDir: string): string[];
}

export const nodeFileSystem: FileSystemPort = {
	read(absolutePath) {
		try {
			return readFileSync(absolutePath, "utf8");
		} catch {
			return "";
		}
	},
	listJavaFiles(absoluteDir) {
		const out: string[] = [];
		const walk = (dir: string): void => {
			let entries: Dirent[];
			try {
				entries = readdirSync(dir, { withFileTypes: true });
			} catch {
				return;
			}
			for (const entry of entries) {
				const path = join(dir, entry.name);
				if (entry.isDirectory()) walk(path);
				else if (entry.name.endsWith(".java")) out.push(path);
			}
		};
		walk(absoluteDir);
		return out;
	},
};

/** Reads `systemProp.<key>` from gradle.properties. */
export function gradleProp(root: string, key: string, fs: FileSystemPort): string | null {
	const match = new RegExp(String.raw`^\s*systemProp\.${key}\s*=\s*(.+)$`, "m").exec(
		fs.read(join(root, "gradle.properties")),
	);
	return match?.[1] ? match[1].trim() : null;
}

/**
 * Finds the debug launch module: in projects generated by the Cosmic dev
 * assistant it is the only module using java-application-conventions. When that
 * fails, fall back to a module name containing "cosmic-debug" -- the root
 * build.gradle deployJar identifies it the same way, so it is template
 * convention rather than a guess.
 */
export function detectDebugModule(
	root: string,
	modules: readonly string[],
	fs: FileSystemPort,
	dirs: ModuleDirMap = {},
): string | null {
	const byPlugin = modules.filter((m) =>
		/java-application-conventions/.test(decomment(fs.read(join(moduleRoot(root, m, dirs), "build.gradle")))),
	);
	if (byPlugin.length === 1) return byPlugin[0] ?? null;
	const byName = modules.filter((m) => /cosmic-debug/.test(m));
	if (byName.length === 1) return byName[0] ?? null;
	return null;
}

export interface AppDetection {
	appClass: string | null;
	appMethod: string | null;
	appFile: string | null;
}

/**
 * `appMethod` value meaning "run the launch class's own main()". The probe host
 * can do that safely only because it carries a no-op `kd.bos.service.bootstrap.Booter`
 * ahead of the platform's (resources/runtime/Booter.java): main() configures,
 * reaches the launcher's start(), and start() -> Booter.main returns at once.
 */
export const APP_METHOD_MAIN = "main";

/**
 * Finds the launch class and its configure-but-do-not-start entry.
 *
 * A probe needs the system properties set without Jetty starting. The Cosmic dev
 * assistant has generated two shapes of launch class:
 *
 *   - older: `Launcher cosmic = devRemote(); cosmic.start();` -- configuration
 *     lives in its own method, which the probe calls alone;
 *   - newer: `CosmicLauncher cosmic = new CosmicLauncher(false); cosmic.setXxx(...);
 *     cosmic.start();` -- everything is inline in main and there is no such method.
 *
 * For the newer shape the answer is main itself, but only when the launcher's
 * start() demonstrably goes through the platform's `Booter.main` -- that call is
 * the one the probe host neutralises. A launcher that starts the server some
 * other way, or whose source is not in the debug module, is left undetected
 * rather than guessed: guessing wrong would start a real server inside a probe.
 */
export function detectApp(
	root: string,
	debugModule: string,
	fs: FileSystemPort,
	dirs: ModuleDirMap = {},
): AppDetection {
	const files = fs.listJavaFiles(join(moduleRoot(root, debugModule, dirs), "src", "main", "java"));
	for (const file of files) {
		const text = decomment(fs.read(file));
		const mainAt = text.search(/static\s+void\s+main\s*\(/);
		if (mainAt < 0 || !/Launcher\b/.test(text)) continue;
		const pkg = /^\s*package\s+([\w.]+)\s*;/m.exec(text);
		const cls = basename(file, ".java");
		const body = text.slice(mainAt);
		return {
			appClass: (pkg?.[1] ? `${pkg[1]}.` : "") + cls,
			appMethod: configureMethod(body) ?? (startsThroughBooter(body, files, fs) ? APP_METHOD_MAIN : null),
			appFile: file,
		};
	}
	return { appClass: null, appMethod: null, appFile: null };
}

/** The first `XxxLauncher x = method();` inside the main body (the older template). */
function configureMethod(mainBody: string): string | null {
	return /\b\w*Launcher\s+\w+\s*=\s*(\w+)\s*\(\s*\)/.exec(mainBody)?.[1] ?? null;
}

/**
 * True when main calls `x.start()` on a launcher declared in main, and that
 * launcher's own source (somewhere in the debug module) calls `Booter.main`.
 */
function startsThroughBooter(mainBody: string, files: readonly string[], fs: FileSystemPort): boolean {
	const declared = /\b(\w*Launcher)\s+(\w+)\s*=/.exec(mainBody);
	if (!declared?.[1] || !declared[2]) return false;
	const [, type, variable] = declared;
	if (!new RegExp(String.raw`\b${variable}\s*\.\s*start\s*\(\s*\)`).test(mainBody)) return false;
	const source = files.find((path) => basename(path, ".java") === type);
	return source !== undefined && /\bBooter\s*\.\s*main\s*\(/.test(decomment(fs.read(source)));
}

export interface AutoDetected {
	isv: string | null;
	/** The project's own systemProp.cosmic_home. S2.2 treats this as the only authoritative source. */
	cosmicHome: string | null;
	modules: string[];
	/** Modules settings.gradle relocates with `projectDir`; absent ones live at `<root>/<module>`. */
	moduleDirs: Record<string, string>;
	debugModule: string | null;
	codeModules: string[];
	unresolvedDeps: string[];
	appClass: string | null;
	appMethod: string | null;
}

export function detect(root: string, fs: FileSystemPort): AutoDetected {
	const settings = fs.read(join(root, "settings.gradle"));
	const modules = parseIncludes(settings);
	const moduleDirs = parseProjectDirs(settings);
	const debugModule = detectDebugModule(root, modules, fs, moduleDirs);
	// Code modules are collected along the transitive dependency closure: shared
	// modules commonly hang off a business module rather than off the debug module.
	const code = debugModule
		? resolveCodeModules(debugModule, (m) => fs.read(join(moduleRoot(root, m, moduleDirs), "build.gradle")), modules)
		: { modules: [], unresolved: [] };
	const app = debugModule
		? detectApp(root, debugModule, fs, moduleDirs)
		: { appClass: null, appMethod: null, appFile: null };
	return {
		isv: gradleProp(root, "developer_flag", fs),
		cosmicHome: gradleProp(root, "cosmic_home", fs),
		modules,
		moduleDirs,
		debugModule,
		codeModules: code.modules,
		unresolvedDeps: code.unresolved,
		appClass: app.appClass,
		appMethod: app.appMethod,
	};
}
